//! TypeScript export for the protocol shared by plugin processes and the Ora host.

use std::fs;
use std::path::Path;

use ora_plugin_protocol::*;

const GENERATED_FILE_HEADER: &str = "// This file was generated by `cargo xtask export-contracts`. Do not edit this file manually.\n";

/// Refreshes Rust-owned plugin DTOs and method constants without touching hand-written SDK files.
pub(crate) fn run(workspace_root: &Path) -> Result<(), Box<dyn std::error::Error>> {
    let output_directory = workspace_root.join("packages/plugin-sdk/src/protocol");
    fs::create_dir_all(&output_directory)?;
    remove_stale_typescript_bindings(&output_directory)?;
    export_typescript_bindings_to(&output_directory)?;

    let constants = render_constants();
    fs::write(output_directory.join("constants.ts"), constants)?;
    Ok(())
}

/// Removes only files owned by ts-rs so hand-written transport and barrel modules survive.
fn remove_stale_typescript_bindings(directory: &Path) -> Result<(), Box<dyn std::error::Error>> {
    const TS_RS_HEADER: &str = "// This file was generated by [ts-rs]";

    for entry in fs::read_dir(directory)? {
        let path = entry?.path();
        if path.is_dir() {
            remove_stale_typescript_bindings(&path)?;
        } else if path.extension().is_some_and(|extension| extension == "ts")
            && fs::read_to_string(&path)?.starts_with(TS_RS_HEADER)
        {
            fs::remove_file(path)?;
        }
    }
    Ok(())
}

