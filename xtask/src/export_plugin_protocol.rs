#[cfg(test)]
mod tests {
    use super::render_constants;

    /// Locks snake_case wire names and guards against restoring SDK-only spellings.
    #[test]
    fn renders_snake_case_methods() {
        let source = render_constants();

        assert!(source.contains("agent/list_models"));
        assert!(source.contains("effect/verify_ready"));
        assert!(source.contains("ora/childprocess/close_stdin"));
        assert!(!source.contains("agent/listModels"));
    }
}
